def calculate_team_total_rating(players: list) -> int:
    rating = 0
    for player in players:
        rating += player.get_rating()
    return rating


def elves_concert(elfs: list) -> None:
    for elf in elfs:
        elf.play_elf_song()


def feast_of_the_dwarves(dwarfs: list) -> None:
    for dwarf in dwarfs:
        dwarf.eat_favourite_dish()
